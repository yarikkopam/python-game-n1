# --- Заголовок ------------------------------------
title = "ЗАБРОШЕННАЯ КУЗНИЦА"
frame = "=" * 22
print(frame)
print(f" {title} ")
print(frame)
print()

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в старую кузницу. Здесь пахнет железом и золой, "
      "а в углу тлеет уголёк.")
print()

# --- Настройка героя -------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, воля — по одному числу в строке:")
health = int(input())
strength = int(input())
agility = int(input())
will = int(input())  # Четвёртая характеристика воля героя

# --- Расчёт урона ----------------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2
# Запас сил здоровье + воля 5. Деление нацело, чтобы было целое число
stamina = (health + will) // 5

# --- Формуляр героя --------------------------------
print("Характеристики героя:")
print(f"Здоровье:   {health}")
print(f"Сила:       {strength}")
print(f"Ловкость:   {agility}")
print(f"Воля:       {will}")
print()
print(f"Урон героя:        {damage:.1f}")
print(f"Критический урон:  {crit_damage:.1f}")
print(f"Запас сил:         {stamina}")
print()

# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - потрогать наковальню")
print("5 - осмотреть полки")
print("6 - тренировка")
print()

# --- Выбор действия --------------------------------
choice = input()

if choice == "1":
    print("Вы внимательно осматриваетесь. В кузнице тихо, "
          "только изредка потрескивает уголёк.")

elif choice == "2":
    stamina = stamina - 3
    print("Вы решительно идёте вперёд, обходя груды старого хлама. "
          "Спина ноет от напряжения.")

elif choice == "3":
    # Отдых восстанавливает меньше, чем тратит дорога,
    # чтобы герой не мог бесконечно ходить и отдыхать.
    stamina = stamina + 1
    print("Вы присаживаетесь на край скамьи и переводите дух. "
          "Силы понемногу возвращаются.")

elif choice == "4":
    # Проверка наковальни наклониться и потрогать небольшая трата сил.
    stamina = stamina - 1
    print("Вы осторожно касаетесь наковальни. Металл ещё хранит "
          "слабое тепло — кузница заброшена не так давно.")

elif choice == "5":
    # Поиск на полках требует сил и внимания.
    # Найденная эмблема слегка укрепляет волю героя.
    will = will + 1
    stamina = stamina - 2
    print("На пыльной полке вы находите старую эмблему "
          "кузнечного цеха. Что-то внутри вас крепнет.")

elif choice == "6":
    # --- Тренировочный бой --------------------------
    strikes = 6
    total_damage = 0
    crit_count = 0

    print("Вы подходите к старому чучелу, сколоченному из брёвен "
          "и обтянутому ржавыми листами железа.")
    print("Его оставил прошлый кузнец — тренировался, когда заказов "
          "не было.")
    print()
    print(f"Наносите {strikes} ударов.")

    for i in range(1, strikes + 1):
        # Каждый третий удар критический
        if i % 3 == 0:
            hit_damage = crit_damage
            crit_count = crit_count + 1
            print(f"Удар {i}: {hit_damage:.1f} — критический!")
        else:
            hit_damage = damage
            print(f"Удар {i}: {hit_damage:.1f}")

        total_damage = total_damage + hit_damage

    # --- Итог боя -----------------------------------
    print()
    print(f"Итог: {strikes} ударов, критических ударов: {crit_count}")
    print(f"Общий урон: {total_damage:.1f}")
    print(f"Средний урон: {total_damage / strikes:.1f}")

    # Тренировка утомляет сильнее, чем дорога
    stamina = stamina - 4

else:
    print("Такого действия нет. Выберите номер из списка.")

# --- Строка состояния героя ------------------------
print()
print(f"Здоровье: {health:5d} Запас сил: {stamina:5d}")

# --- Прощание --------------------------------------
print()
print(frame)
print(f" Удачи, {hero_name}! ")
print(frame)
